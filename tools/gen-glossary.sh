#!/usr/bin/env bash
# gen-glossary.sh — the declared vocabulary, projected into the code.
#
# A definition that lives only in `tools/glossary/` is a definition nobody reads while editing the type it
# describes. This generator writes it where the type is declared (`vocabulary-projection`, "The definition
# reaches the owning type as KDoc"), and emits a skeleton type for a `concept` row whose type no file declares
# yet ("A declared concept with no file is emitted as a skeleton").
#
# The projection is **additive**: a type whose KDoc block already exists is left exactly as it is and reported
# as `not projected`, because a generator that rewrites a hand-written comment block is a generator that
# deletes what a person wrote. The generated block is
#
#   /**
#    * <the declaration's one sentence>
#    *
#    * declared by <key>; edit the declaration, not this block.
#    */
#
# A skeleton carries that same KDoc and a generated marker, and declares no members. It is written only when
# its file is absent; a file that exists — hand-written or generated on an earlier run — is never overwritten.
#
# `--check` verifies instead of writing: every projection must be present and its text must be the one the
# declaration states, and a skeleton must exist with its marker. A difference is printed naming the type and
# the row and the exit is 1, and nothing is written (`vocabulary-projection`, "The check mode fails instead of
# writing"). This is the shape `tools/gen-feature-list.sh --check-classification` already uses.
#
# The skeleton's package is the profile's, not a literal here: `tools/glossary/index.json` `projections` names
# the root and the package. No Gradle task runs this generator (task 4.3): it is a person's command.
#
# Reads and writes text files only: no build, no device, no network. Exit 0 when every projection was written
# (or, with `--check`, is current), 1 when `--check` finds one that is not, 2 on a usage or layout error.
#
# Usage: gen-glossary.sh [--root <dir>] [--check]
set -uo pipefail

prog=gen-glossary
root=""
check_mode=0
while [ $# -gt 0 ]; do
  case "$1" in
    --root) [ $# -ge 2 ] && [ "${2#--}" = "$2" ] || { printf '%s: %s needs a value\n' "$prog" "$1" >&2; exit 2; }; root="${2:-}"; shift 2 ;;
    --check) check_mode=1; shift ;;
    -h|--help) sed -n '2,37p' "${BASH_SOURCE[0]}"; exit 0 ;;
    *) printf '%s: unknown argument %s\n' "$prog" "$1" >&2; exit 2 ;;
  esac
done
[ -n "$root" ] || root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
script_dir=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)

gdir="$root/tools/glossary"
index="$gdir/index.json"
[ -f "$index" ] || { printf '%s: no %s\n' "$prog" "$index" >&2; exit 2; }
jq -e . "$index" >/dev/null 2>&1 || { printf '%s: %s is not valid JSON\n' "$prog" "$index" >&2; exit 2; }
command -v jq >/dev/null 2>&1 || { printf '%s: jq is required\n' "$prog" >&2; exit 2; }

skeleton_root=$(jq -r '.projections.skeletonRoot // "app/src/main/java"' "$index")
skeleton_package=$(jq -r '.projections.skeletonPackage // empty' "$index")
skeleton_suffix=$(jq -r '.projections.skeletonSuffix // ""' "$index")

tmp=$(mktemp -d "${TMPDIR:-/tmp}/gen-glossary.XXXXXX") || exit 2
trap 'rm -rf "$tmp"' EXIT

: > "$tmp/rows.jsonl"
for f in "$gdir"/*.json; do
  [ -f "$f" ] || continue
  [ "$(basename "$f")" = "index.json" ] && continue
  scope=$(basename "$f" .json)
  jq -c --arg scope "$scope" --arg file "${f#"$root"/}" '.rows[]? | . + {__scope: $scope, __file: $file}' "$f" >> "$tmp/rows.jsonl"
done

projected=0
skeletons=0
skipped=0
missing=0
modified=0
findings="$tmp/findings.txt"
: > "$findings"

# The reading copy: one heading per row, so a person reads the declaration without opening twelve JSON files. It
# is generated from the same rows the projections are, and `--check` holds it to the same text (design D3).
glossary_md="$tmp/GLOSSARY.md"
{
  printf '# Glossary — the declared vocabulary\n\n'
  printf 'Generated by `tools/gen-glossary.sh` from `tools/glossary/*.json`. Edit the declaration, not this file.\n'
  jq -r -s 'sort_by(.key)[] |
    "\n## \(.key)\n\n\(.definition)\n\n" +
    "- not: \(.not // "")\n" +
    "- home: \(if (.home // "") != "" then .home elif .__scope == "concept" then "concept" else "feature/" + .__scope end)\n" +
    "- surfaces: \((.surfaces // {}) | to_entries | map("\(.key)=\(.value)") | join(", "))\n" +
    "- anchor: \((.anchor // []) | join("; "))\n"' "$tmp/rows.jsonl"
} > "$glossary_md"

kdoc_block() { # $1 definition, $2 key, $3 indentation of the declaration line
  i=${3-}
  printf '%s/**\n%s * %s\n%s *\n%s * declared by %s; edit the declaration, not this block.\n%s */\n' \
    "$i" "$i" "$1" "$i" "$i" "$2" "$i"
}

while IFS= read -r row; do
  [ -n "$row" ] || continue
  key=$(printf '%s' "$row" | jq -r '.key // ""')
  definition=$(printf '%s' "$row" | jq -r '.definition // ""')
  type=$(printf '%s' "$row" | jq -r '.surfaces.type // ""')
  home=$(printf '%s' "$row" | jq -r '.home // (if .__scope == "concept" then "concept" else "feature/" + .__scope end)')
  [ -n "$type" ] || continue
  [ -n "$definition" ] || continue

  # the file that declares the type, if any — the declaration is the line the name is introduced on. The
  # native bridge under `app/src/main/cpp` is not read: the project does not own libosmscout's words (design D1).
  declared=$(find "$root/app/src/main" "$root/auto/src/main" "$root/core/src/main" -type f \( -name '*.kt' -o -name '*.java' \) \
    -not -path "$root/app/src/main/cpp/*" \
    -exec awk -v t="$type" '
      /^[[:space:]]*(public |internal |private |abstract |final |open |sealed |data |value |enum )*(class|interface|object)[[:space:]]+[A-Za-z_][A-Za-z0-9_]*/ {
        m = $0
        sub(/^.*(class|interface|object)[[:space:]]+/, "", m)
        sub(/[^A-Za-z0-9_].*$/, "", m)
        if (m == t) { printf "%s:%d\n", FILENAME, FNR; exit }
      }' {} \; 2>/dev/null | head -1)

  indent=""
  if [ -n "$declared" ]; then
    indent=$(sed -n "${declared##*:}p" "${declared%:*}" | sed -e 's/[^ ].*//')
  fi
  block=$(kdoc_block "$definition" "$key" "$indent")

  if [ -n "$declared" ]; then
    df=${declared%:*}
    dl=${declared##*:}
    # the block immediately above the declaration, if there is one
    prev=$((dl - 1))
    existing=""
    if [ "$prev" -ge 1 ]; then
      if sed -n "${prev}p" "$df" | grep -q '\*/'; then
        existing=$(awk -v end="$prev" '
          NR <= end { line[NR] = $0 }
          END {
            start = 0
            for (i = end; i >= 1; i--) { if (line[i] ~ /^[[:space:]]*\/\*\*/ || line[i] ~ /^[[:space:]]*\/\*/) { start = i; break } }
            if (start == 0) exit
            for (i = start; i <= end; i++) print line[i]
          }' "$df")
      fi
    fi
    if [ -n "$existing" ]; then
      if [ "$check_mode" -eq 1 ]; then
        if [ "$existing" = "$block" ]; then
          skipped=$((skipped + 1))
        else
          modified=$((modified + 1))
          printf '%s: modified %s %s:%s — the KDoc above the declaration is not the declared text (row %s)\n' \
            "$prog" "$type" "${df#"$root"/}" "$dl" "$key" >> "$findings"
        fi
      else
        skipped=$((skipped + 1))
        printf '%s: not projected %s %s:%s — a KDoc block is already there and is not rewritten\n' \
          "$prog" "$type" "${df#"$root"/}" "$dl" >&2
      fi
      continue
    fi
    if [ "$check_mode" -eq 1 ]; then
      missing=$((missing + 1))
      printf '%s: missing %s %s:%s — the type carries no projected definition (row %s)\n' \
        "$prog" "$type" "${df#"$root"/}" "$dl" "$key" >> "$findings"
    else
      {
        if [ "$dl" -gt 1 ]; then sed -n "1,$((dl - 1))p" "$df"; fi
        printf '%s\n' "$block"
        sed -n "${dl},\$p" "$df"
      } > "$tmp/rewrite"
      cat "$tmp/rewrite" > "$df"
      projected=$((projected + 1))
    fi
    continue
  fi

  # nothing declares the type: a concept row emits a skeleton, and only when its file is absent. Any other row
  # declares a word, not a file, so it is not a projection site and is reported rather than refused (design D8).
  case "$home" in
    concept) ;;
    *)
      skipped=$((skipped + 1))
      if [ "$check_mode" -eq 1 ]; then
        printf '%s: not projected %s — no file declares it and it is not a concept row (row %s)\n' \
          "$prog" "$type" "$key" >&2
      fi
      continue
      ;;
  esac
  [ -n "$skeleton_package" ] || { skipped=$((skipped + 1)); continue; }
  target="$root/$skeleton_root/$(printf '%s' "$skeleton_package" | tr '.' '/')/$type$skeleton_suffix.kt"
  marker="// generated by gen-glossary.sh from $key — edit the declaration, not this file."
  if [ "$check_mode" -eq 1 ]; then
    if [ -f "$target" ] && grep -Fq "$marker" "$target" && grep -Fq "$definition" "$target"; then
      skeletons=$((skeletons + 1))
    else
      missing=$((missing + 1))
      printf '%s: missing %s %s — the declared concept has no skeleton (row %s)\n' \
        "$prog" "$type" "${target#"$root"/}" "$key" >> "$findings"
    fi
    continue
  fi
  if [ -f "$target" ]; then
    skipped=$((skipped + 1))
    printf '%s: not projected %s %s — the file exists and is not overwritten\n' "$prog" "$type" "${target#"$root"/}" >&2
    continue
  fi
  mkdir -p "$(dirname "$target")"
  {
    printf '%s\n' "$marker"
    printf 'package %s\n\n' "$skeleton_package"
    kdoc_block "$definition" "$key"
    printf 'class %s%s\n' "$type" "$skeleton_suffix"
  } > "$target"
  skeletons=$((skeletons + 1))
done < "$tmp/rows.jsonl"

if [ "$check_mode" -eq 1 ]; then
  if [ ! -f "$gdir/GLOSSARY.md" ]; then
    printf '%s: missing GLOSSARY.md — the reading copy the declaration generates is absent\n' "$prog" >> "$findings"
  elif ! cmp -s "$glossary_md" "$gdir/GLOSSARY.md"; then
    printf '%s: modified GLOSSARY.md — the reading copy is not the declared text\n' "$prog" >> "$findings"
  fi
  if [ -s "$findings" ]; then
    cat "$findings"
    printf '%s: red missing=%s modified=%s current=%s skeletons=%s — nothing was written\n' \
      "$prog" "$missing" "$modified" "$skipped" "$skeletons"
    exit 1
  fi
  printf '%s: green current=%s skeletons=%s — every projection is the declaration'"'"'s text\n' "$prog" "$skipped" "$skeletons"
  exit 0
fi

cat "$glossary_md" > "$gdir/GLOSSARY.md"
printf '%s: projected=%s skeletons=%s skipped=%s\n' "$prog" "$projected" "$skeletons" "$skipped"
exit 0
